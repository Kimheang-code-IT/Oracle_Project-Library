-- ===============================
-- 1) USERS
-- ===============================
CREATE TABLE users (
  user_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username  VARCHAR2(50) UNIQUE NOT NULL,
  password  VARCHAR2(100) NOT NULL,
  role      VARCHAR2(10) NOT NULL
             CONSTRAINT chk_users_role
               CHECK (role IN ('ADMIN','USER'))
);

-- ===============================
-- 2) CATEGORIES
-- ===============================
CREATE TABLE categories (
  category_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  category_name  VARCHAR2(100) UNIQUE NOT NULL,
  description    CLOB,
  book_count     NUMBER DEFAULT 0 NOT NULL,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Trigger: update updated_at on categories
CREATE OR REPLACE TRIGGER trg_categories_upd_ts
  BEFORE UPDATE ON categories
  FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- Trigger: maintain book_count in categories
CREATE OR REPLACE TRIGGER trg_categories_count
  AFTER INSERT OR DELETE ON books
  FOR EACH ROW
DECLARE
  v_delta PLS_INTEGER;
BEGIN
  IF INSERTING THEN
    v_delta := 1;
  ELSIF DELETING THEN
    v_delta := -1;
  END IF;
  UPDATE categories
     SET book_count = book_count + v_delta
   WHERE category_id = NVL(:NEW.category_id, :OLD.category_id);
END;
/

-- ===============================
-- 3) BOOKS
-- ===============================
CREATE TABLE books (
  book_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  category_id  NUMBER NOT NULL
                CONSTRAINT fk_books_cat
                  REFERENCES categories(category_id),
  barcode      VARCHAR2(50) UNIQUE NOT NULL,
  title        VARCHAR2(200) UNIQUE NOT NULL,
  author       VARCHAR2(200),
  description  CLOB,
  cover_image  BLOB,
  pdf_file     BLOB,
  total_copies NUMBER DEFAULT 1 NOT NULL,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Trigger: update updated_at on books
CREATE OR REPLACE TRIGGER trg_books_upd_ts
  BEFORE UPDATE ON books
  FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- ===============================
-- 4) BORROWS
-- ===============================
CREATE TABLE borrows (
  borrow_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id     NUMBER NOT NULL
               CONSTRAINT fk_borrows_user
                 REFERENCES users(user_id),
  book_id     NUMBER NOT NULL
               CONSTRAINT fk_borrows_book
                 REFERENCES books(book_id),
  borrow_date DATE DEFAULT SYSDATE NOT NULL,
  duration    NUMBER DEFAULT 14 NOT NULL,
  return_date DATE,
  due_date    DATE GENERATED ALWAYS AS (borrow_date + duration) VIRTUAL,
  total_days  NUMBER GENERATED ALWAYS AS (
                  CASE WHEN return_date IS NOT NULL
                       THEN return_date - borrow_date
                       ELSE NULL END
               ) VIRTUAL,
  status      VARCHAR2(10) DEFAULT 'BORROWED' NOT NULL
               CONSTRAINT chk_borrows_status
                 CHECK (status IN ('BORROWED','RETURNED','OVERDUE'))
);

-- Trigger: set status on borrows
CREATE OR REPLACE TRIGGER trg_borrows_status_upd
  BEFORE INSERT OR UPDATE ON borrows
  FOR EACH ROW
BEGIN
  IF :NEW.return_date IS NOT NULL THEN
    :NEW.status := 'RETURNED';
  ELSIF SYSDATE > :NEW.due_date THEN
    :NEW.status := 'OVERDUE';
  ELSE
    :NEW.status := 'BORROWED';
  END IF;
END;
/

