-- ===============================
-- 6) VIEW: full book info + availability
-- ===============================
CREATE OR REPLACE VIEW vw_book_info AS
SELECT
  b.barcode,
  c.category_name,
  b.title,
  b.author,
  b.description,
  b.total_copies,
  NVL(a.borrowed_count, 0) AS borrowed_count,
  b.total_copies - NVL(a.borrowed_count, 0) AS available_copies,
  b.created_at,
  b.updated_at
FROM books b
JOIN categories c ON b.category_id = c.category_id
LEFT JOIN (
  SELECT book_id,
         SUM(CASE WHEN status = 'BORROWED' THEN 1 ELSE 0 END) AS borrowed_count
    FROM borrows
   GROUP BY book_id
) a ON b.book_id = a.book_id;

-- ===============================
-- 7) FUNCTION: fetch book by barcode
-- ===============================
CREATE OR REPLACE FUNCTION get_book_by_barcode (
  p_barcode IN VARCHAR2
) RETURN SYS_REFCURSOR IS
  rc SYS_REFCURSOR;
BEGIN
  OPEN rc FOR
    SELECT * FROM vw_book_info WHERE barcode = p_barcode;
  RETURN rc;
END;
/


-- ================================================
-- 1) Package specification
-- ================================================
CREATE OR REPLACE PACKAGE category_pkg AS

  -- Create a new category
  PROCEDURE add_category(
    p_name        IN VARCHAR2,
    p_description IN CLOB
  );

  -- Read a single category by ID
  PROCEDURE get_category(
    p_id           IN  NUMBER,
    p_name         OUT VARCHAR2,
    p_description  OUT CLOB,
    p_count        OUT NUMBER,
    p_created_at   OUT TIMESTAMP,
    p_updated_at   OUT TIMESTAMP
  );

  -- List all categories (returns a REF CURSOR)
  PROCEDURE list_categories(
    p_cursor OUT SYS_REFCURSOR
  );

  -- Update an existing category
  PROCEDURE update_category(
    p_id           IN NUMBER,
    p_name         IN VARCHAR2,
    p_description  IN CLOB
  );

  -- Delete a category
  PROCEDURE delete_category(
    p_id IN NUMBER
  );

END category_pkg;
/

-- ================================================
-- 2) Package body
-- ================================================
CREATE OR REPLACE PACKAGE BODY category_pkg AS

  PROCEDURE add_category(
    p_name        IN VARCHAR2,
    p_description IN CLOB
  ) IS
  BEGIN
    INSERT INTO categories(category_name, description)
    VALUES(p_name, p_description);
    COMMIT;
  END add_category;


  PROCEDURE get_category(
    p_id           IN  NUMBER,
    p_name         OUT VARCHAR2,
    p_description  OUT CLOB,
    p_count        OUT NUMBER,
    p_created_at   OUT TIMESTAMP,
    p_updated_at   OUT TIMESTAMP
  ) IS
  BEGIN
    SELECT category_name,
           description,
           book_count,
           created_at,
           updated_at
      INTO p_name,
           p_description,
           p_count,
           p_created_at,
           p_updated_at
      FROM categories
     WHERE category_id = p_id;
  END get_category;


  PROCEDURE list_categories(
    p_cursor OUT SYS_REFCURSOR
  ) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT category_id,
             category_name,
             description,
             book_count,
             created_at,
             updated_at
        FROM categories
       ORDER BY category_id;
  END list_categories;


  PROCEDURE update_category(
    p_id           IN NUMBER,
    p_name         IN VARCHAR2,
    p_description  IN CLOB
  ) IS
  BEGIN
    UPDATE categories
       SET category_name = p_name,
           description   = p_description,
           updated_at    = SYSTIMESTAMP
     WHERE category_id = p_id;
    COMMIT;
  END update_category;


  PROCEDURE delete_category(
    p_id IN NUMBER
  ) IS
  BEGIN
    DELETE FROM categories
     WHERE category_id = p_id;
    COMMIT;
  END delete_category;

END category_pkg;
